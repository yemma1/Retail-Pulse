-- Drop tables if they already exist (in reverse dependency order)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE ORDER_ITEMS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE ORDERS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE PRODUCTS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE CATEGORIES CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE CUSTOMERS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- ----------------------------------------------------------------------------
-- 1. TABLE: CUSTOMERS
-- Stores customer profiles, locations, and registration dates
-- ----------------------------------------------------------------------------
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_NAME       VARCHAR2(100) NOT NULL,
    EMAIL               VARCHAR2(120) NOT NULL UNIQUE,
    CITY                VARCHAR2(60) NOT NULL,
    STATE               VARCHAR2(60) NOT NULL,
    COUNTRY             VARCHAR2(60) DEFAULT 'USA' NOT NULL,
    REGISTRATION_DATE   DATE DEFAULT SYSDATE NOT NULL
);

COMMENT ON TABLE CUSTOMERS IS 'Stores demographic and profile information for retail customers.';
COMMENT ON COLUMN CUSTOMERS.CUSTOMER_ID IS 'Unique identifier for each customer (Primary Key).';
COMMENT ON COLUMN CUSTOMERS.CUSTOMER_NAME IS 'Full name of the customer.';
COMMENT ON COLUMN CUSTOMERS.EMAIL IS 'Unique email address of the customer.';
COMMENT ON COLUMN CUSTOMERS.CITY IS 'City of residence for regional sales analytics.';
COMMENT ON COLUMN CUSTOMERS.STATE IS 'State of residence.';
COMMENT ON COLUMN CUSTOMERS.COUNTRY IS 'Country of residence.';
COMMENT ON COLUMN CUSTOMERS.REGISTRATION_DATE IS 'Date customer joined the platform.';

-- ----------------------------------------------------------------------------
-- 2. TABLE: CATEGORIES
-- Stores product category taxonomy
-- ----------------------------------------------------------------------------
CREATE TABLE CATEGORIES (
    CATEGORY_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME       VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION         VARCHAR2(255)
);

COMMENT ON TABLE CATEGORIES IS 'Product category taxonomy lookup table.';
COMMENT ON COLUMN CATEGORIES.CATEGORY_ID IS 'Unique identifier for each product category (Primary Key).';
COMMENT ON COLUMN CATEGORIES.CATEGORY_NAME IS 'Standardized name of the category.';
COMMENT ON COLUMN CATEGORIES.DESCRIPTION IS 'Brief explanation of product types in this category.';

-- ----------------------------------------------------------------------------
-- 3. TABLE: PRODUCTS
-- Stores retail merchandise catalog, pricing, and inventory
-- ----------------------------------------------------------------------------
CREATE TABLE PRODUCTS (
    PRODUCT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_NAME        VARCHAR2(150) NOT NULL,
    CATEGORY_ID         NUMBER NOT NULL,
    PRICE               NUMBER(10, 2) NOT NULL,
    STOCK_QUANTITY      NUMBER(8) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_PROD_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES (CATEGORY_ID),
    CONSTRAINT CHK_PROD_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CHK_PROD_STOCK CHECK (STOCK_QUANTITY >= 0)
);

COMMENT ON TABLE PRODUCTS IS 'Catalog of retail merchandise, pricing, and stock levels.';
COMMENT ON COLUMN PRODUCTS.PRODUCT_ID IS 'Unique identifier for each product (Primary Key).';
COMMENT ON COLUMN PRODUCTS.PRODUCT_NAME IS 'Commercial name of the product.';
COMMENT ON COLUMN PRODUCTS.CATEGORY_ID IS 'Foreign key referencing the parent category.';
COMMENT ON COLUMN PRODUCTS.PRICE IS 'Catalog list price per unit in USD.';
COMMENT ON COLUMN PRODUCTS.STOCK_QUANTITY IS 'Current warehouse inventory quantity.';

-- ----------------------------------------------------------------------------
-- 4. TABLE: ORDERS
-- Stores customer purchasing transactions and fulfillment status
-- ----------------------------------------------------------------------------
CREATE TABLE ORDERS (
    ORDER_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID         NUMBER NOT NULL,
    ORDER_DATE          DATE DEFAULT SYSDATE NOT NULL,
    ORDER_STATUS        VARCHAR2(30) DEFAULT 'Completed' NOT NULL,
    PAYMENT_METHOD      VARCHAR2(50) DEFAULT 'Credit Card' NOT NULL,
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID),
    CONSTRAINT CHK_ORDER_STATUS CHECK (ORDER_STATUS IN ('Completed', 'Shipped', 'Processing', 'Cancelled')),
    CONSTRAINT CHK_PAYMENT_METHOD CHECK (PAYMENT_METHOD IN ('Credit Card', 'PayPal', 'Debit Card', 'Bank Transfer', 'Apple Pay'))
);

COMMENT ON TABLE ORDERS IS 'Header records for customer retail sales transactions.';
COMMENT ON COLUMN ORDERS.ORDER_ID IS 'Unique order transaction number (Primary Key).';
COMMENT ON COLUMN ORDERS.CUSTOMER_ID IS 'Foreign key referencing the customer who placed the order.';
COMMENT ON COLUMN ORDERS.ORDER_DATE IS 'Timestamp when the order was placed.';
COMMENT ON COLUMN ORDERS.ORDER_STATUS IS 'Fulfillment state: Completed, Shipped, Processing, or Cancelled.';
COMMENT ON COLUMN ORDERS.PAYMENT_METHOD IS 'Payment instrument used for the transaction.';

-- ----------------------------------------------------------------------------
-- 5. TABLE: ORDER_ITEMS
-- Stores individual line items for each order, including unit price and discount
-- ----------------------------------------------------------------------------
CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ORDER_ID            NUMBER NOT NULL,
    PRODUCT_ID          NUMBER NOT NULL,
    QUANTITY            NUMBER(6) NOT NULL,
    UNIT_PRICE          NUMBER(10, 2) NOT NULL,
    DISCOUNT            NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    CONSTRAINT FK_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEMS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID),
    CONSTRAINT CHK_ITEM_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_ITEM_PRICE CHECK (UNIT_PRICE >= 0),
    CONSTRAINT CHK_ITEM_DISCOUNT CHECK (DISCOUNT >= 0)
);

COMMENT ON TABLE ORDER_ITEMS IS 'Detailed transaction line items specifying quantities and applied discounts.';
COMMENT ON COLUMN ORDER_ITEMS.ORDER_ITEM_ID IS 'Unique line item identifier (Primary Key).';
COMMENT ON COLUMN ORDER_ITEMS.ORDER_ID IS 'Foreign key referencing the parent order.';
COMMENT ON COLUMN ORDER_ITEMS.PRODUCT_ID IS 'Foreign key referencing the purchased product.';
COMMENT ON COLUMN ORDER_ITEMS.QUANTITY IS 'Number of units purchased.';
COMMENT ON COLUMN ORDER_ITEMS.UNIT_PRICE IS 'Price per unit at time of sale.';
COMMENT ON COLUMN ORDER_ITEMS.DISCOUNT IS 'Discount amount deducted from total line item sale.';

-- ----------------------------------------------------------------------------
-- PERFORMANCE INDEXES
-- Optimizes JOIN and filter performance for analytical reporting queries
-- ----------------------------------------------------------------------------
CREATE INDEX IDX_CUST_CITY ON CUSTOMERS (CITY);
CREATE INDEX IDX_PROD_CATEGORY ON PRODUCTS (CATEGORY_ID);
CREATE INDEX IDX_ORDERS_DATE ON ORDERS (ORDER_DATE);
CREATE INDEX IDX_ORDERS_STATUS ON ORDERS (ORDER_STATUS);
CREATE INDEX IDX_ORDERS_CUST ON ORDERS (CUSTOMER_ID);
CREATE INDEX IDX_ITEMS_ORDER ON ORDER_ITEMS (ORDER_ID);
CREATE INDEX IDX_ITEMS_PROD ON ORDER_ITEMS (PRODUCT_ID);

COMMIT;
